namespace {
struct Row {
	const char *name;
	int64_t value;
};

template <size_t N>
void add(Dictionary &all, const char *name, const Row (&rows)[N]) {
	Dictionary values;
	for (const Row &r : rows) values[String(r.name)] = r.value;
	all[String(name)] = values;
}
} // namespace

// The enumerator's own name and value: neither can drift from the enum.
#define CITY_ROW(E, V) Row{ #V, int64_t(E::V) }
#define CITY_ROW_PLAIN(V) Row{ #V, int64_t(V) }
// One enum; with a count (its COUNT), the compiler refuses a list that leaves one out.
#define CITY_ENUM(NAME, ...) 	{ 		static constexpr Row rows[] = { __VA_ARGS__ }; 		add(d, NAME, rows); 	}
#define CITY_ENUM_ALL(NAME, COUNT, ...) 	{ 		static constexpr Row rows[] = { __VA_ARGS__ }; 		static_assert(std::size(rows) == size_t(COUNT), NAME ": every value listed"); 		add(d, NAME, rows); 	}


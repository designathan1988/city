"""The register's generated view: doc/problems.md written from doc/problems.jsonl, by area (the schema's order), then status (the
order a problem moves in), then id. `python tools/atlas/render.py` writes it; `--check` writes nothing and exits 0 only when the
view on disk is what it would write (the generated-files gate asks this, so a hand edit of the view cannot stand)."""
import argparse
import os
import sys

TOOLS_DIR = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
if TOOLS_DIR not in sys.path:
    sys.path.insert(0, TOOLS_DIR)
from atlas import problems as register  # noqa: E402

VIEW = "doc/problems.md"


def _line(p):
    parts = [f"**{p['id']}** {p['title']}", f"owner `{p['owner']}`", f"cause: {p['cause']}"]
    if p.get("cause") == register.UNKNOWN and p.get("reading"):
        parts.append(f"to read: {p['reading']}")
    parts.append(f"closes when: {p['criterion']}")
    if p.get("spec"):
        parts.append(f"spec: {p['spec']}")
    if p.get("fix"):
        parts.append(f"fix: {p['fix']}")
    return "- " + "; ".join(parts)


def text(reg):
    """The view's whole text for a loaded register."""
    statuses = list(register.MOVES)
    counts = {s: sum(1 for p in reg.problems if p.get("status") == s) for s in statuses}
    out = ["# Problems", "",
           f"Generated by `tools/atlas/render.py` from `{register.REGISTER}`, the one register (written only through "
           "`python tools/atlas/cli.py problems`): do not edit.",
           f"{len(reg.problems)} problems: " + ", ".join(f"{s} {n}" for s, n in counts.items() if n) + "."]
    for area in reg.enum("area"):
        mine = [p for p in reg.problems if p.get("area") == area]
        if not mine:
            continue
        out += ["", f"## {area} ({len(mine)})"]
        for status in statuses:
            these = sorted((p for p in mine if p.get("status") == status), key=lambda p: int(p["id"].rsplit("-", 1)[1]))
            if these:
                out += ["", f"### {status} ({len(these)})", ""] + [_line(p) for p in these]
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="write nothing; exit 0 only when the view on disk is current")
    ap.add_argument("--root", default=register.ROOT, help="the repository (the tests give a folder of their own)")
    args = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):  # UTF-8 whatever the console's code page; a caller's own buffer is left as it is
        sys.stdout.reconfigure(encoding="utf-8")
    reg = register.Register(root=args.root)
    data = text(reg).encode("utf-8")
    path = os.path.join(args.root, VIEW)
    if args.check:
        current = None
        if os.path.isfile(path):
            with open(path, "rb") as fh:
                current = fh.read()
        if current != data:
            print(f"{VIEW} is not what tools/atlas/render.py writes from {register.REGISTER}: run it, never edit the view")
            return 1
        print(f"{VIEW} is current ({len(reg.problems)} problems)")
        return 0
    with open(path, "wb") as fh:
        fh.write(data)
    print(f"{VIEW} written ({len(reg.problems)} problems)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

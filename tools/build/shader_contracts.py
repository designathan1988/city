"""The values the shaders share with the C++ core and the scripts, made from one table (tools/build/shader_contracts.json).

    python tools/build/shader_contracts.py           writes each group's native/src/core/shader_contracts/<group>.h and
                                                      project/render/shaders/contracts/<group>.gdshaderinc, and
                                                      native/src/core/shader_contracts/{contract,all}.h
    python tools/build/shader_contracts.py --check   exits 1 when any is not what the table makes, or one is there it does not
                                                      make (quick's task)

The table is in groups by domain: a renderer and its shaders take their group's file, nothing else. An entry's type:
  int, float   one value; a float is written as the table gives it (a number or an expression the two languages read the
               same): C++ takes it through float(...), the shading language as it is, the scripts as a double.
  vec3         three such floats: a float[3] in C++, a vec3 in the shaders, a Vector3 for the scripts.
  ints, floats a named set of them ("values": {name: value}), each a constant of its own.
  enum         C++ gets its declaration (in "namespace" when given), the shaders one constant a value (prefixed by
               "shader_prefix", of "shader_type"), numbered from "start" (0 when absent); "count" names the one after the last.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TABLE = ROOT / "tools/build/shader_contracts.json"
HEADERS = ROOT / "native/src/core/shader_contracts"
INCLUDES = ROOT / "project/render/shaders/contracts"
NOTE = "Generated by tools/build/shader_contracts.py from tools/build/shader_contracts.json: edit the table, never this file."
VEC3 = 3


def _number(name: str, value) -> str:
    if isinstance(value, bool) or not isinstance(value, (int, float, str)):
        raise ValueError(f"{name}: a value is a number or an expression")
    return str(value)


def _enum_values(e: dict) -> list:
    """(name, number) of each value, the count after them."""
    names = list(e["values"]) + ([e["count"]] if e.get("count") else [])
    start = int(e.get("start", 0))
    return [(n, start + i) for i, n in enumerate(names)]


def _scalars(e: dict) -> list:
    """(name, value) of an int, float, ints or floats entry."""
    if e["type"] in ("int", "float"):
        return [(e["name"], _number(e["name"], e["value"]))]
    return [(n, _number(n, v)) for n, v in e["values"].items()]


def _shader_names(e: dict) -> list:
    if e["type"] in ("int", "float", "ints", "floats"):
        return [n for n, _ in _scalars(e)]
    if e["type"] == "vec3":
        return [e["name"]]
    if e["type"] == "enum":
        return [e.get("shader_prefix", "") + n for n, _ in _enum_values(e)]
    raise ValueError(f"{e['name']}: unknown type {e['type']}")


def _array(group: str) -> str:
    return f"SHADER_CONTRACTS_{group.upper()}"


def group_header(group: str, g: dict) -> str:
    lines = [
        f"// What the shaders share with the C++ core and the scripts: {g['doc']}. {NOTE}",
        f"// The shaders read the same through project/render/shaders/contracts/{group}.gdshaderinc; the scripts through",
        f"// CityCore::constants \"shader\" ({_array(group)} below, gathered in core/shader_contracts/all.h).",
        "#pragma once",
        "",
        '#include "core/shader_contracts/contract.h"',
        "",
        "#include <cstdint>",
        "",
        "namespace city {",
        "",
    ]
    rows = []  # (name, size, C++ expressions)
    for e in g["entries"]:
        kind = e["type"]
        lines.append(f"// {e['doc']}")
        if kind in ("int", "ints"):
            for name, value in _scalars(e):
                lines.append(f"constexpr int {name} = {value};")
                rows.append((name, 1, [name]))
        elif kind in ("float", "floats"):
            for name, value in _scalars(e):
                lines.append(f"constexpr float {name} = float({value});")
                rows.append((name, 1, [value]))  # the scripts take the table's decimal as a double, as their literals did
        elif kind == "vec3":
            values = [_number(e["name"], v) for v in e["value"]]
            if len(values) != VEC3:
                raise ValueError(f"{e['name']}: a vec3 has three values")
            lines.append(f"constexpr float {e['name']}[3] = {{ {', '.join(f'float({v})' for v in values)} }};")
            rows.append((e["name"], VEC3, [f"{e['name']}[{i}]" for i in range(VEC3)]))  # a Vector3 holds floats
        elif kind == "enum":
            values = _enum_values(e)
            start = int(e.get("start", 0))
            listed = [f"{values[0][0]} = {start}" if start else values[0][0]] + [n for n, _ in values[1:]]
            declaration = f"{e['cpp']} {{ {', '.join(listed)} }};"
            space = e.get("namespace")
            lines.append(f"namespace {space} {{ {declaration} }}" if space else declaration)
            scoped = e["cpp"].startswith("enum class")
            prefix = e.get("shader_prefix", "")
            qualified = f"{space}::" if space else ""
            for name, _ in values:
                rows.append((prefix + name, 1, [f"{qualified}{e['name']}::{name}" if scoped else f"{qualified}{name}"]))
        else:
            raise ValueError(f"{e['name']}: unknown type {kind}")
    lines += ["", "// Every value above by the name the shaders give it, for the scripts.", f"constexpr ShaderContract {_array(group)}[] = {{"]
    lines += [f"\t{{ \"{name}\", {size}, {{ {', '.join(f'double({x})' for x in exprs)} }} }}," for name, size, exprs in rows]
    lines += ["};", "", "} // namespace city", ""]
    return "\n".join(lines)


def group_include(group: str, g: dict) -> str:
    guard = f"CONTRACTS_{group.upper()}_INCLUDED"
    lines = [f"// What the shaders share with the C++ core and the scripts: {g['doc']}. {NOTE}", f"#ifndef {guard}", f"#define {guard}", ""]
    for e in g["entries"]:
        kind = e["type"]
        lines.append(f"// {e['doc']}")
        if kind in ("int", "float", "ints", "floats"):
            shader_type = "int" if kind in ("int", "ints") else "float"
            lines += [f"const {shader_type} {name} = {value};" for name, value in _scalars(e)]
        elif kind == "vec3":
            lines.append(f"const vec3 {e['name']} = vec3({', '.join(_number(e['name'], v) for v in e['value'])});")
        else:
            shader_type = e.get("shader_type", "int")
            prefix = e.get("shader_prefix", "")
            for name, number in _enum_values(e):
                lines.append(f"const {shader_type} {prefix}{name} = {float(number) if shader_type == 'float' else number};")
    lines += ["", "#endif", ""]
    return "\n".join(lines)


def contract_header() -> str:
    return "\n".join([
        f"// What a value the shaders share looks like to the scripts: its name and one number, or a vec3's three. {NOTE}",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        "namespace city {",
        "",
        "struct ShaderContract {",
        "\tconst char *name;",
        "\tint size;",
        "\tdouble value[3];",
        "};",
        "",
        "// One group's values (core/shader_contracts/<group>.h).",
        "struct ShaderContractGroup {",
        "\tconst ShaderContract *rows;",
        "\tsize_t count;",
        "};",
        "",
        "} // namespace city",
        "",
    ])


def all_header(groups: dict) -> str:
    lines = [f"// Every group of the values the shaders share, for CityCore::constants \"shader\". {NOTE}", "#pragma once", ""]
    lines += [f'#include "core/shader_contracts/{g}.h"' for g in groups]
    lines += ["", "#include <iterator>", "", "namespace city {", "", "constexpr ShaderContractGroup SHADER_CONTRACT_GROUPS[] = {"]
    lines += [f"\t{{ {_array(g)}, std::size({_array(g)}) }}," for g in groups]
    lines += ["};", "", "} // namespace city", ""]
    return "\n".join(lines)


def outputs(table: dict) -> dict:
    groups = table["groups"]
    seen = {}  # every name the shaders and the scripts read, once across the groups
    for group, g in groups.items():
        for e in g["entries"]:
            for name in _shader_names(e):
                if name in seen:
                    raise ValueError(f"{name}: named twice ({seen[name]}, {group})")
                seen[name] = group
    made = {HEADERS / "contract.h": contract_header(), HEADERS / "all.h": all_header(groups)}
    for group, g in groups.items():
        made[HEADERS / f"{group}.h"] = group_header(group, g)
        made[INCLUDES / f"{group}.gdshaderinc"] = group_include(group, g)
    return made


def _strays(made: dict) -> list:
    """Files in the output folders the table does not make (a group gone or renamed); a Godot .uid beside an include is its own."""
    kept = set(made) | {p.with_name(p.name + ".uid") for p in made}
    return sorted(p for folder in (HEADERS, INCLUDES) if folder.is_dir() for p in folder.iterdir() if p not in kept)


def main(argv: list) -> int:
    table = json.loads(TABLE.read_text(encoding="utf-8"))
    made = outputs(table)
    if "--check" in argv:
        stale = [p for p, text in made.items() if not p.exists() or p.read_text(encoding="utf-8") != text] + _strays(made)
        for p in stale:
            print(f"stale: {p.relative_to(ROOT).as_posix()} (python tools/build/shader_contracts.py)")
        return 1 if stale else 0
    for p, text in made.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {p.relative_to(ROOT).as_posix()}")
    for p in _strays(made):
        print(f"not made by the table: {p.relative_to(ROOT).as_posix()} (delete it)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

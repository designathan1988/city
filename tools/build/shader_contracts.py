"""The values the C++ core and the shaders both read, made from one table (tools/build/shader_contracts.json).

    python tools/build/shader_contracts.py           writes native/src/core/shader_contracts.h and
                                                      project/render/shaders/shader_contracts.gdshaderinc
    python tools/build/shader_contracts.py --check   exits 1 when either is not what the table makes (quick's task)

A float's value is written as the table gives it (a number or an expression the two languages read the same); C++ takes it
through float(...), the shading language as it is. An enum gives C++ its declaration and the shaders one constant a value.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TABLE = ROOT / "tools/build/shader_contracts.json"
HEADER = ROOT / "native/src/core/shader_contracts.h"
INCLUDE = ROOT / "project/render/shaders/shader_contracts.gdshaderinc"
GUARD = "SHADER_CONTRACTS_INCLUDED"
NOTE = "Generated by tools/build/shader_contracts.py from tools/build/shader_contracts.json: edit the table, never this file."


def _number(entry):
    value = entry["value"]
    if isinstance(value, bool) or not isinstance(value, (int, float, str)):
        raise ValueError(f"{entry['name']}: a value is a number or an expression")
    return str(value)


def header(table: dict) -> str:
    lines = [
        f"// What the C++ core and the shaders both read. {NOTE}",
        "// The shaders read the same through project/render/shaders/shader_contracts.gdshaderinc; the scripts through",
        "// CityCore::constants \"shader\" (SHADER_CONTRACTS below).",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace city {",
        "",
    ]
    rows = []
    for e in table["entries"]:
        lines.append(f"// {e['doc']}")
        if e["type"] == "int":
            lines.append(f"constexpr int {e['name']} = {_number(e)};")
            rows.append((e["name"], e["name"]))
        elif e["type"] == "float":
            lines.append(f"constexpr float {e['name']} = float({_number(e)});")
            rows.append((e["name"], _number(e)))  # the scripts take the table's decimal as a double, as their literals did
        elif e["type"] == "enum":
            values = list(e["values"])
            if e.get("count"):
                values.append(e["count"])
            lines.append(f"{e['cpp']} {{ {', '.join(values)} }};")
            scoped = e["cpp"].startswith("enum class")
            prefix = e.get("shader_prefix", "")
            for v in values:
                rows.append((prefix + v, f"{e['name']}::{v}" if scoped else v))
        else:
            raise ValueError(f"{e['name']}: unknown type {e['type']}")
    lines += [
        "",
        "// Every value above by the name the shaders give it, for the scripts.",
        "struct ShaderContract {",
        "\tconst char *name;",
        "\tdouble value;",
        "};",
        "constexpr ShaderContract SHADER_CONTRACTS[] = {",
    ]
    lines += [f"\t{{ \"{name}\", double({expr}) }}," for name, expr in rows]
    lines += ["};", "", "} // namespace city", ""]
    return "\n".join(lines)


def include(table: dict) -> str:
    lines = [f"// What the shaders and the C++ core both read. {NOTE}", f"#ifndef {GUARD}", f"#define {GUARD}", ""]
    for e in table["entries"]:
        lines.append(f"// {e['doc']}")
        if e["type"] in ("int", "float"):
            lines.append(f"const {e['type']} {e['name']} = {_number(e)};")
        else:
            kind = e.get("shader_type", "int")
            values = list(e["values"]) + ([e["count"]] if e.get("count") else [])
            prefix = e.get("shader_prefix", "")
            for i, v in enumerate(values):
                lines.append(f"const {kind} {prefix}{v} = {float(i) if kind == 'float' else i};")
    lines += ["", "#endif", ""]
    return "\n".join(lines)


def outputs(table: dict) -> dict:
    return {HEADER: header(table), INCLUDE: include(table)}


def main(argv: list) -> int:
    table = json.loads(TABLE.read_text(encoding="utf-8"))
    made = outputs(table)
    if "--check" in argv:
        stale = [str(p.relative_to(ROOT)) for p, text in made.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"stale: {p} (python tools/build/shader_contracts.py)")
        return 1 if stale else 0
    for p, text in made.items():
        p.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
